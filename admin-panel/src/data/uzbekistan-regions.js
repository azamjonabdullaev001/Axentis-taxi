// Плоский список для быстрого поиска
// ──────────────────────────────────────────
const FLAT_LOCATIONS = []

for (const reg of UZBEKISTAN_REGIONS) {
  for (const dist of reg.districts) {
    for (const city of dist.cities) {
      FLAT_LOCATIONS.push({
        name: city.name,
        district: dist.district,
        region: reg.region,
        lat: city.lat,
        lng: city.lng,
        // Полный путь в формате Google Maps
        fullPath: `${reg.region}, ${dist.district}, ${city.name}`,
        // Поисковая строка (нижний регистр) — для быстрого фильтра
        _search: `${city.name} ${dist.district} ${reg.region}`.toLowerCase(),
      })
    }
  }
}

/**
 * Поиск по вводу диспетчера.
 * Возвращает массив совпадений с полным путём.
 * @param {string} query — текст ввода
 * @param {number} limit — макс. результатов
 */
export function searchLocations(query, limit = 10) {
  if (!query || query.length < 1) return []
  const q = query.toLowerCase().trim()
  const results = []
  for (const loc of FLAT_LOCATIONS) {
    if (loc._search.includes(q)) {
      results.push(loc)
      if (results.length >= limit) break
    }
  }
  return results
}

